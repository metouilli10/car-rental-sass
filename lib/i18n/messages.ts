export type Messages = WidenMessageLeaves<typeof messagesFr>;

export function getMessages(locale: AppLocale): Messages {
  return locale === "ar" ? messagesAr : messagesFr;
}

/** Read a nested string by dot path, e.g. `shell.sidebar.dashboard` */
export function messageAt(dict: Messages, path: string): string {
  const parts = path.split(".");
  let cur: unknown = dict as unknown as Record<string, unknown>;
  for (const p of parts) {
    if (cur && typeof cur === "object" && p in cur) {
      cur = (cur as Record<string, unknown>)[p];
    } else {
      return path;
    }
  }
  return typeof cur === "string" ? cur : path;
}

/** Replace `{name}` placeholders in a template string */
export function interpolate(
  template: string,
  vars: Record<string, string | number>
): string {
  return template.replace(/\{(\w+)\}/g, (_, key: string) =>
    vars[key] != null ? String(vars[key]) : `{${key}}`
  );
}
